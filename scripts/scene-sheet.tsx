/**
 * Scene sheet generator.
 *
 * Renders every environment × lighting pass with a character planted on the
 * ground line, so you can eyeball parallax, palettes and framing without
 * opening Remotion.
 *
 *   npm run scene-sheet              # preview/scene-sheet.{html,png}
 *   npm run scene-sheet -- --no-shot
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { renderToStaticMarkup } from 'react-dom/server';
import { CharacterRig } from '../src/rig/Character';
import { SceneLayer, WeatherFront } from '../src/rig/environments';
import { castSceneSettings } from '../src/rig/cast';
import { samplePose, GROUND_Y, CHARACTER_X } from '../src/rig/gait';
import { SCENES, TIMES_OF_DAY } from '../src/rig/types';
import type { Weather } from '../src/rig/types';

const OUT_DIR = 'preview';
const FRAME = 48;
const FPS = 30;

/** The weathers the sheet demonstrates, in caption order. */
const WEATHER_ROW: (Weather | 'clear')[] = ['clear', 'rain', 'snow', 'fog'];

function panel(scene: string, timeOfDay: string, weather: Weather | 'clear', castId: string, motion: 'walk' | 'sit' | 'talk' | 'idle'): string {
  const settings = castSceneSettings(castId, {
    motion,
    scene: scene as never,
    timeOfDay: timeOfDay as never,
    weather,
    followCamera: true,
    scale: 1.18,
  });
  const pose = samplePose(settings, FRAME, FPS);
  const distance = pose.distance * settings.scale;
  const art = renderToStaticMarkup(
    <svg viewBox="0 0 1280 720" xmlns="http://www.w3.org/2000/svg">
      <SceneLayer scene={scene} distance={distance} direction={1} timeOfDay={timeOfDay as never} weather={weather} parallax={0.7} time={FRAME / FPS} />
      <ellipse cx={CHARACTER_X} cy={GROUND_Y + 4} rx={52 * settings.scale} ry={8 * settings.scale} fill="#26352E" opacity={0.18} />
      <g transform={`translate(${CHARACTER_X} ${GROUND_Y}) scale(${settings.scale})`}>
        <CharacterRig settings={settings} frame={FRAME} fps={FPS} />
      </g>
      <WeatherFront weather={weather} timeOfDay={timeOfDay as never} distance={distance} direction={1} time={FRAME / FPS} />
    </svg>,
  );
  const weatherNote = weather === 'clear' ? 'no overlay' : weather;
  return `<figure class="cell"><div class="art">${art}</div><figcaption><b>${scene}</b><span>${timeOfDay} · ${weatherNote} · ${castId} · ${motion}</span></figcaption></figure>`;
}

const castFor: Record<string, string> = { street: 'milo', park: 'juno', room: 'kwame', backdrop: 'ada' };
const motionFor: Record<string, 'walk' | 'sit' | 'talk' | 'idle'> = { street: 'walk', park: 'walk', room: 'walk', backdrop: 'talk' };

const cells = SCENES.flatMap((s) =>
  TIMES_OF_DAY.flatMap((t) =>
    WEATHER_ROW.map((w) => panel(s.id, t.id, w, castFor[s.id] ?? 'milo', motionFor[s.id] ?? 'walk')),
  ),
);

const html = `<!doctype html><html><head><meta charset="utf-8"><title>Stride — scene sheet</title>
<style>
  :root { color-scheme: light; }
  body { margin:0; padding:28px 30px 40px; background:#F5F4EF; font-family: system-ui, sans-serif; color:#26352E; }
  h1 { font-family: Georgia, serif; font-size:30px; margin:0 0 4px; }
  p.lede { margin:0 0 22px; color:#6B7A70; font-size:13px; }
  .grid { display:grid; grid-template-columns: repeat(4, 1fr); gap:18px; }
  .cell { margin:0; background:#FFFDF6; border:1px solid #E2E5DE; border-radius:12px; overflow:hidden; }
  .art { aspect-ratio: 16/9; }
  .art svg { width:100%; height:100%; display:block; }
  figcaption { display:flex; justify-content:space-between; align-items:baseline; padding:8px 12px 10px; border-top:1px solid #EDEFE9; }
  figcaption b { font-size:14px; text-transform:capitalize; }
  figcaption span { font-size:11px; color:#8A968D; }
</style></head><body>
<h1>Stride — scene sheet</h1>
<p class="lede">Every environment × lighting × weather (frame ${FRAME}), with the front weather pass over the character. Generated by <code>npm run scene-sheet</code>.</p>
<div class="grid">${cells.join('')}</div>
</body></html>`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(`${OUT_DIR}/scene-sheet.html`, html);
console.log(`Wrote ${OUT_DIR}/scene-sheet.html`);

if (!process.argv.includes('--no-shot')) {
  const { chromium } = await import('@playwright/test');
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, deviceScaleFactor: 1.25 });
  await page.goto(`file://${process.cwd()}/${OUT_DIR}/scene-sheet.html`);
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${OUT_DIR}/scene-sheet.png`, fullPage: true });
  await browser.close();
  console.log(`Wrote ${OUT_DIR}/scene-sheet.png`);
}
