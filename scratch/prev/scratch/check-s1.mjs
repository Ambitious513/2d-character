import { chromium } from '@playwright/test';
const BASE = 'http://localhost:5173';
const errors = [];
const browser = await chromium.launch({ args: ['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
page.on('console', m => { if (m.type()==='error') errors.push('console: '+m.text()); });
page.on('pageerror', e => errors.push('pageerror: '+e.message));
await page.goto(BASE + '/#/docs', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('[data-docs-player="WalkScene"]', { timeout: 20000 });
await page.waitForTimeout(1800);
console.log('title:', await page.title());
console.log('hero frame:', await page.locator('[data-docs-frame="WalkScene"]').textContent(), '| btn:', await page.locator('.docs-play-btn').getAttribute('aria-label'));
await page.locator('.docs-play-btn').click();
await page.waitForTimeout(350);
const f1 = await page.locator('[data-docs-frame="WalkScene"]').textContent();
await page.waitForTimeout(500);
const f2 = await page.locator('[data-docs-frame="WalkScene"]').textContent();
console.log('pause holds frame:', f1 === f2, f1, f2);
await page.screenshot({ path: 'screenshots/s1-overview.png' });
for (const id of ['quickstart','export','architecture']) {
  await page.locator(`.docs-nav a[href="#/docs/${id}"]`).click();
  await page.waitForTimeout(900);
  console.log(id, '-> hash', await page.evaluate(() => location.hash), '| active:', await page.locator('.docs-nav a.active').textContent());
}
await page.screenshot({ path: 'screenshots/s1-architecture.png' });
await page.locator('.docs-code-copy').first().click();
await page.waitForTimeout(300);
console.log('toast visible:', await page.locator('.docs-toast').isVisible());
await page.getByRole('link', { name: 'Studio', exact: true }).click();
await page.waitForSelector('[data-character="milo"]', { timeout: 15000 });
console.log('back to studio ok, hash:', await page.evaluate(() => location.hash));
await page.close();
const m = await browser.newPage({ viewport: { width: 390, height: 844 } });
m.on('pageerror', e => errors.push('mobile pageerror: '+e.message));
m.on('console', c => { if (c.type()==='error') errors.push('mobile console: '+c.text()); });
await m.goto(BASE + '/#/docs', { waitUntil: 'domcontentloaded' });
await m.waitForSelector('[data-docs-player="WalkScene"]');
await m.waitForTimeout(1200);
const overflow = await m.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
console.log('mobile overflow:', overflow);
if (overflow > 1) errors.push('mobile overflow ' + overflow);
await m.screenshot({ path: 'screenshots/s1-mobile.png' });
await browser.close();
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console/page errors');
process.exit(errors.length ? 1 : 0);
